def _build_citation_html(citations: list[StatuteCitation]) -> str:
    parts = []
    for c in citations:
        penalty_line = f"<br/>Penalty: {c.penalty}" if c.penalty else ""
        notice_line = (
            f"<br/>Notice period: {c.notice_period_days} days"
            if c.notice_period_days
            else ""
        )
        parts.append(
            f'<div class="citation">'
            f"<strong>{c.section} — {c.section_title}</strong>"
            f"<em>{c.act}</em><br/>"
            f"Forum: {c.forum}"
            f"{penalty_line}{notice_line}<br/>"
            f"<blockquote>{c.excerpt[:300]}{'…' if len(c.excerpt) > 300 else ''}</blockquote>"
            f"</div>"
        )
    return "\n".join(parts)


def _render_html(notice: LegalNotice, body: str) -> str:
    citations_html = _build_citation_html(notice.citations)
    return _HTML_TEMPLATE.format(
        case_id=notice.case_id,
        notice_id=notice.id,
        date=datetime.now(timezone.utc).strftime("%d %B %Y"),
        body=body.replace("<", "&lt;").replace(">", "&gt;"),
        citations_html=citations_html,
        sha256_placeholder="[computed after PDF generation]",
    )


# ── PDF generation ────────────────────────────────────────────────────────────

def _try_weasyprint(html: str) -> bytes | None:
    try:
        from weasyprint import HTML  # type: ignore
        return HTML(string=html).write_pdf()
    except Exception:
        return None


def _fallback_pdf(html: str, notice: LegalNotice, body: str) -> bytes:
    """
    Minimal fallback: encode the HTML as UTF-8 bytes wrapped in a
    single-page PDF using pure Python (no external library).
    This is only used in test / offline environments.
    """
    # Embed as a PDF with a single FlateDecode stream
    import zlib

    text_content = (
        f"LEGAL NOTICE\n"
        f"Case ID: {notice.case_id}\n"
        f"Notice ID: {notice.id}\n"
        f"Date: {datetime.now(timezone.utc).strftime('%d %B %Y')}\n\n"
        f"{body}\n\n"
        f"--- Statutory Citations ---\n"
        + "\n".join(
            f"{c.section} ({c.act}): {c.excerpt[:200]}"
            for c in notice.citations
        )
    )
    # Build a minimal valid PDF manually
    obj1 = b"1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n"
    obj2 = b"2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n"
    obj3 = (
        b"3 0 obj\n<< /Type /Page /Parent 2 0 R "
        b"/MediaBox [0 0 595 842] /Contents 4 0 R "
        b"/Resources << /Font << /F1 << /Type /Font /Subtype /Type1 "
        b"/BaseFont /Helvetica >> >> >> >>\nendobj\n"
    )
    # Encode text as PDF content stream
    stream_text = "BT\n/F1 10 Tf\n50 800 Td\n"
    for line in text_content.split("\n")[:60]:
        safe = line.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)").replace("\r", "")
        stream_text += f"({safe[:80]}) Tj\n0 -14 Td\n"
    stream_text += "ET\n"
    stream_bytes = stream_text.encode("latin-1", errors="replace")

    obj4 = (
        f"4 0 obj\n<< /Length {len(stream_bytes)} >>\nstream\n".encode()
        + stream_bytes
        + b"\nendstream\nendobj\n"
    )

    body_bytes = obj1 + obj2 + obj3 + obj4
    xref_pos = len(b"%PDF-1.4\n") + len(body_bytes)
    xref = (
        b"xref\n0 5\n"
        b"0000000000 65535 f \n"
        + b"".join(
            f"{len(b'%PDF-1.4\n') + sum(len(o) for o in [obj1, obj2, obj3, obj4][:i]):010d} 00000 n \n".encode()
            for i in range(4)
        )
    )
    trailer = (
        b"trailer\n<< /Size 5 /Root 1 0 R >>\n"
        + f"startxref\n{xref_pos}\n%%EOF\n".encode()
    )
    return b"%PDF-1.4\n" + body_bytes + xref + trailer


def render_pdf(notice: LegalNotice, body: str) -> bytes:
    html = _render_html(notice, body)
    pdf_bytes = _try_weasyprint(html)
    if pdf_bytes is None:
        pdf_bytes = _fallback_pdf(html, notice, body)
    return pdf_bytes


# ── Settlement URL generation ─────────────────────────────────────────────────

def generate_settlement_token(notice: LegalNotice) -> str:
    """
    Create a JWT-signed settlement token for the respondent.
    Signed with SETTLEMENT_SECRET_KEY, 30-day expiry.
    """
    from jose import jwt  # type: ignore

    now = datetime.now(timezone.utc)
    payload = {
        "sub": notice.id,
        "case_id": notice.case_id,
        "iat": int(now.timestamp()),
        "exp": int((now + timedelta(days=30)).timestamp()),
        "type": "settlement",
    }
    return jwt.encode(
        payload, settings.settlement_secret_key, algorithm="HS256"
    )


def generate_settlement_url(notice: LegalNotice, token: str) -> str:
    return f"{settings.settlement_base_url}/{notice.case_id}?token={token}"


# ── Top-level function called by clinic router ────────────────────────────────

def approve_and_generate(notice: LegalNotice, approved_body: str) -> tuple[str, str, str, str]:
    """
    Render the approved notice to PDF, hash it, and generate settlement URL.

    Returns (pdf_path, pdf_hash, settlement_token, settlement_url)
    """
    Path(settings.pdf_dir).mkdir(parents=True, exist_ok=True)

    pdf_bytes = render_pdf(notice, approved_body)

    # SHA-256 hash for tamper-evidence
    pdf_hash = hashlib.sha256(pdf_bytes).hexdigest()

    # Re-render with the actual hash embedded
    html_final = _render_html(notice, approved_body).replace(
        "[computed after PDF generation]", pdf_hash
    )
    final_pdf_bytes = _try_weasyprint(html_final) or pdf_bytes

    # Write to disk
    filename = f"{notice.case_id}_{notice.id}.pdf"
    pdf_path = str(Path(settings.pdf_dir) / filename)
    Path(pdf_path).write_bytes(final_pdf_bytes)

    # Settlement token + URL
    token = generate_settlement_token(notice)
    url = generate_settlement_url(notice, token)

    return pdf_path, pdf_hash, token, url

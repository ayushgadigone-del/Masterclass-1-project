"""
pdf_service.py — HTML → PDF generation with SHA-256 hash and settlement URL.

Uses WeasyPrint to render an HTML template to a PDF.
Falls back to a plain-text PDF writer (reportlab-free) if WeasyPrint is
not available in the environment, so tests run without system dependencies.

On approval:
  1. Render the approved notice body as a styled HTML document
  2. Convert to PDF bytes
  3. Compute SHA-256 hash of the PDF bytes (tamper-evidence)
  4. Write to PDF_DIR/<case_id>_<notice_id>.pdf
  5. Generate a JWT-signed settlement token (30-day expiry)
  6. Return (pdf_path, pdf_hash, settlement_url)
"""
from __future__ import annotations

import hashlib
import os
from datetime import datetime, timezone, timedelta
from pathlib import Path

from app.config import settings
from app.models.notice import LegalNotice, StatuteCitation

# ── HTML template for the legal notice PDF ────────────────────────────────────

